#!/usr/bin/env python3
"""
Convert the DE-BIAS vocabulary spreadsheet into data/debias-vocabulary.js, the
list of contested terms MapGaps flags under EXT-UI-LING-CONT.

    pip install openpyxl
    python3 -I scripts/import-debias.py path/to/DE-BIAS_Vocabulary.xlsx

Reads the "English" sheet. Follows the vocabulary's own Status column: only
entries active in the DE-BIAS Knowledge Graph are used; entries excluded from
detection, deprecated, or still work in progress are left out.

Only short fields are kept (ID, label, suggestion, alternatives, bias areas,
link). The long "Contentious issue" explanations stay with DE-BIAS: each term
links to its source instead.
"""
import json
import re
import sys
from pathlib import Path

import openpyxl

OUT = Path(__file__).resolve().parent.parent / "data" / "debias-vocabulary.js"
ACTIVE = (
    "This entry was transferred to/updated in the Knowledge Graph",
    "This entry was updated after it was transferred to the Knowledge Graph",
)


def clean(value):
    return re.sub(r"\s+", " ", str(value)).strip() if value is not None else ""


def main(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    sheets = {name.strip().lower(): wb[name] for name in wb.sheetnames}
    rows = [r for r in sheets["english"].iter_rows(values_only=True) if any(clean(c) for c in r)]
    header = [clean(c) for c in rows[0]]
    col = {name: header.index(name) for name in header if name}

    def get(row, name):
        i = col.get(name)
        return clean(row[i]) if i is not None and i < len(row) else ""

    terms, skipped = [], {}
    for row in rows[1:]:
        status = get(row, "Status")
        label = get(row, "Contentious labels")
        if not label:
            continue
        if status not in ACTIVE:
            skipped[status or "(no status)"] = skipped.get(status or "(no status)", 0) + 1
            continue
        terms.append({
            "id": get(row, "ID"),
            "label": label,
            "suggestion": get(row, "Suggestion description"),
            "alternatives": [a.strip() for a in get(row, "Suggested alternatives").split(";") if a.strip()],
            "categories": [c.strip() for c in get(row, "Category/Bias areas").split(";") if c.strip()],
            "contextDependent": bool(get(row, "Disambiguation needed?")),
            "link": get(row, "Link / reference"),
        })

    data = {
        "source": "DE-BIAS Vocabulary (" + re.sub(r"^[0-9a-f]{8}-", "", Path(path).name) + "), English sheet",
        "terms": terms,
    }
    OUT.write_text(
        "/*\n * Contested terms from the DE-BIAS vocabulary, generated by scripts/import-debias.py.\n"
        " * Do not edit by hand: update the spreadsheet and re-run the script.\n */\n"
        "(function (root, debias) {\n"
        "  if (typeof module === 'object' && module.exports) module.exports = debias;\n"
        "  else root.MAPGAPS_DEBIAS = debias;\n"
        "})(typeof self !== 'undefined' ? self : this, "
        + json.dumps(data, indent=1, ensure_ascii=False)
        + ");\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(terms)} terms to {OUT}")
    for status, n in sorted(skipped.items(), key=lambda kv: -kv[1]):
        print(f"  left out {n:3d}: {status}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
